class StationStatusChip extends StatelessWidget {
  const StationStatusChip({super.key, required this.status});

  final String status;

  @override
  Widget build(BuildContext context) {
    final (label, color) = switch (status) {
      'pending_payment' => ('Awaiting payment', Colors.orange),
      'paid' => ('Paid', const Color(0xFF2E7D32)),
      'used' => ('Used', Colors.blueGrey),
      'expired' => ('Expired', Colors.red),
      'cancelled' => ('Cancelled', Colors.grey),
      'refunded' => ('Refunded', Colors.purple),
      'pending' => ('Payment pending', Colors.orange),
      'failed' => ('Payment failed', Colors.red),
      _ => (status, Colors.grey),
    };
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
      decoration: BoxDecoration(
        color: color.withValues(alpha: 0.12),
        borderRadius: BorderRadius.circular(20),
        border: Border.all(color: color.withValues(alpha: 0.4)),
      ),
      child: Text(
        label,
        style: TextStyle(
          color: color,
          fontSize: 12,
          fontWeight: FontWeight.bold,
        ),
      ),
    );
  }
}

